// Translates one Variant Compare choice into a visual override for the
// Option B layer: color diffs swap the fill class; radius sets the corner
// radius; size / padding / spacing / weight grow or shrink the box by the
// delta from Option A's value (so picking A is always "no change").
// `side` is 'A', 'B', or a hand-typed `{ custom }` value from inline editing
// in Compare — a custom color name maps onto the matching fill class.
export function diffEffect(diff, side) {
  const custom = isCustomResolution(side) ? side.custom : null
  const value = parseFloat(custom ?? (side === 'A' ? diff.optionA : diff.optionB))
  const base = parseFloat(diff.optionA)
  const effect = {}
  const cls = custom != null ? customFillClass(custom) : side === 'A' ? diff.optionAClass : diff.optionBClass
  if (cls) effect.className = cls
  if (Number.isNaN(value)) return effect
  const delta = value - base
  if (/radius/.test(diff.id)) effect.radius = value
  else if (/size/.test(diff.id)) effect.dh = delta
  else if (/padding|spacing/.test(diff.id)) {
    effect.dw = delta * 2
    effect.dh = delta * 2
  } else if (/weight/.test(diff.id)) effect.fontWeight = value
  return effect
}

export function isCustomResolution(side) {
  return typeof side === 'object' && side !== null && typeof side.custom === 'string'
}

// The value a resolution settles on, as display text.
export function resolutionValue(diff, side) {
  if (isCustomResolution(side)) return side.custom
  return side === 'A' ? diff.optionA : diff.optionB
}

// Only fill classes already present in the source are generated by Tailwind,
// so custom color names resolve against the known Block Assemble fills.
function customFillClass(text) {
  const t = text.toLowerCase()
  return ASSEMBLY_FILLS.find((f) => t.includes(f.id))?.className
}

