// Rule-based "AI recommendation" per element type, used by both the
// builder and the manual fallback for elements with no parseable tokens.
export function recommendAssembly(layer) {
  switch (layer.type) {
    case 'button':
      return { rationale: 'A pill gradient with a soft glow matches this file’s primary CTAs.', patch: { shape: 'pill', fill: 'gradient', shadow: 'glow' } }
    case 'input':
      return { rationale: 'Pill-shaped inputs with an outline match the new radius.lg token.', patch: { shape: 'pill', border: 'outline' } }
    case 'card':
      return { rationale: 'A larger radius with a soft shadow separates cards from the page.', patch: { shape: 'rounded', shadow: 'soft' } }
    case 'chip':
      return { rationale: 'Chips read best as violet pills.', patch: { shape: 'pill', fill: 'violet' } }
    case 'toggle':
      return { rationale: 'Use the violet accent for active toggles.', patch: { fill: 'violet' } }
    case 'avatar':
      return { rationale: 'Avatars stay circular; add a soft shadow for depth.', patch: { shape: 'circle', shadow: 'soft' } }
    case 'image':
      return { rationale: 'Round the image to match neighbouring cards.', patch: { shape: 'rounded' } }
    default:
      return { rationale: 'Round the corners slightly to match the design system.', patch: { shape: 'rounded' } }
  }
}

// The artboard frame plus any layers pulled in from the Design System
// library; the frame grows to keep them inside.
export function frameWithLayers(frame, extra = []) {
  if (!frame || !extra.length) return frame
  const bottom = Math.max(frame.height, ...extra.map((l) => l.y + l.height + 16))
  return { ...frame, height: bottom, layers: [...frame.layers, ...extra] }
}

// Which Design System components fit a selected element: `replace` types can
// stand in for it (same role), `insert` types can be dropped into it when it
// is a container.
const REPLACE_GROUPS = {
  button: ['button', 'iconbtn', 'chip'],
  iconbtn: ['button', 'iconbtn', 'chip'],
  chip: ['button', 'iconbtn', 'chip'],
  input: ['input'],
  card: ['card', 'image'],
  image: ['image', 'card'],
  toggle: ['toggle'],
  avatar: ['avatar'],
  tabs: ['tabs', 'bar'],
  bar: ['bar', 'tabs'],
  text: ['chip'],
}
const INSERT_INTO = {
  card: ['button', 'iconbtn', 'chip', 'input', 'toggle', 'avatar'],
  image: ['chip', 'iconbtn', 'avatar'],
  bar: ['iconbtn', 'chip', 'avatar'],
  tabs: ['iconbtn', 'chip'],
}

export function libraryCompat(layer) {
  return {
    replace: new Set(REPLACE_GROUPS[layer.type] ?? []),
    insert: new Set(INSERT_INTO[layer.type] ?? []),
  }
}
